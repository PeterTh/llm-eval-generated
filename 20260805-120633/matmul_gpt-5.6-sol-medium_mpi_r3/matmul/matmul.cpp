#include <mpi.h>

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <limits>
#include <vector>

#include "../common/results_output.hpp"

// Generate pseudo-random values for matrix initialization.
constexpr double getPseudoRndValue(const size_t N, const size_t i,
                                   const size_t j) noexcept {
    return (((i + 1) * (i + j + 1) * 1299709) % (N * N)) /
           static_cast<double>(N * N);
}

// Initialize only the rows assigned to this rank.  Using the global row index
// preserves exactly the matrix generated by the serial implementation.
void initLocalMatrix(std::vector<double>& mat, const size_t N,
                     const size_t firstRow, const size_t rowCount) {
    for (size_t localI = 0; localI < rowCount; ++localI) {
        const size_t globalI = firstRow + localI;
        for (size_t j = 0; j < N; ++j) {
            mat[localI * N + j] = getPseudoRndValue(N, globalI, j);
        }
    }
}

void initMatrix(std::vector<double>& mat, const size_t N) {
    for (size_t i = 0; i < N; ++i) {
        for (size_t j = 0; j < N; ++j) {
            mat[i * N + j] = getPseudoRndValue(N, i, j);
        }
    }
}

// Cache-blocked local GEMM.  The j loop is contiguous for both B and C and is
// consequently easy for the compiler to vectorize.  k is still accumulated in
// increasing order, preserving the serial program's floating-point semantics.
void matrixMultiplyLocal(const std::vector<double>& A,
                         const std::vector<double>& B,
                         std::vector<double>& C, const size_t N,
                         const size_t localRows) {
    constexpr size_t blockI = 32;
    constexpr size_t blockJ = 64;
    constexpr size_t blockK = 64;

    std::fill(C.begin(), C.end(), 0.0);
    const double* const a = A.data();
    const double* const b = B.data();
    double* const c = C.data();

    for (size_t ii = 0; ii < localRows; ii += blockI) {
        const size_t iEnd = std::min(ii + blockI, localRows);
        for (size_t jj = 0; jj < N; jj += blockJ) {
            const size_t jEnd = std::min(jj + blockJ, N);
            for (size_t kk = 0; kk < N; kk += blockK) {
                const size_t kEnd = std::min(kk + blockK, N);
                for (size_t i = ii; i < iEnd; ++i) {
                    double* const cRow = c + i * N;
                    const double* const aRow = a + i * N;
                    for (size_t k = kk; k < kEnd; ++k) {
                        const double aik = aRow[k];
                        const double* const bRow = b + k * N;
#if defined(__GNUC__) || defined(__clang__)
#pragma GCC ivdep
#endif
                        for (size_t j = jj; j < jEnd; ++j) {
                            cRow[j] += aik * bRow[j];
                        }
                    }
                }
            }
        }
    }
}

bool validateLocalResult(const std::vector<double>& A,
                         const std::vector<double>& B,
                         const std::vector<double>& C, const size_t N,
                         const size_t firstRow, const size_t localRows) {
    constexpr size_t checkPoints[] = {0, 1, 2, 3, 4};

    for (const size_t rawI : checkPoints) {
        const size_t i = rawI % N;
        if (i < firstRow || i >= firstRow + localRows) {
            continue;
        }
        const size_t localI = i - firstRow;
        for (const size_t rawJ : checkPoints) {
            const size_t j = rawJ % N;
            double expected = 0.0;
            for (size_t k = 0; k < N; ++k) {
                expected += A[localI * N + k] * B[k * N + j];
            }

            const double actual = C[localI * N + j];
            const double relError =
                std::abs((actual - expected) / (expected + 1e-10));
            if (relError > 1e-6) {
                std::fprintf(stderr,
                             "Validation failed at (%zu, %zu): expected %.10f, "
                             "got %.10f (error: %.10e)\n",
                             i, j, expected, actual, relError);
                return false;
            }
        }
    }
    return true;
}

void printUsage(const char* progName) {
    std::printf("Usage: %s [options]\n", progName);
    std::printf("Options:\n");
    std::printf("  -n <num>     Matrix size N (computes NxN * NxN) (default: 512)\n");
    std::printf("  -v           Enable validation\n");
    std::printf("  -r           Print results for external validation\n");
    std::printf("  -h           Show this help message\n");
}

int main(int argc, char** argv) {
    MPI_Init(&argc, &argv);

    int rank = 0;
    int rankCount = 1;
    MPI_Comm_rank(MPI_COMM_WORLD, &rank);
    MPI_Comm_size(MPI_COMM_WORLD, &rankCount);

    size_t N = 512;
    bool validate = false;
    bool printResults = false;
    bool showHelp = false;
    bool argumentsValid = true;

    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "-n") == 0 && i + 1 < argc) {
            char* end = nullptr;
            const unsigned long long parsed = std::strtoull(argv[++i], &end, 10);
            if (*argv[i] == '\0' || *end != '\0' || parsed == 0 ||
                parsed > std::numeric_limits<size_t>::max()) {
                argumentsValid = false;
            } else {
                N = static_cast<size_t>(parsed);
            }
        } else if (std::strcmp(argv[i], "-v") == 0) {
            validate = true;
        } else if (std::strcmp(argv[i], "-r") == 0) {
            printResults = true;
        } else if (std::strcmp(argv[i], "-h") == 0) {
            showHelp = true;
        } else {
            if (rank == 0) {
                std::printf("Unknown option: %s\n", argv[i]);
            }
            argumentsValid = false;
        }
    }

    if (showHelp || !argumentsValid) {
        if (rank == 0) {
            printUsage(argv[0]);
        }
        MPI_Finalize();
        return argumentsValid ? 0 : 1;
    }

    // MPI_Gatherv uses int counts.  This restriction matters only when the full
    // result was explicitly requested; normal computation and validation have
    // no collective count limitation.
    if (printResults && N > static_cast<size_t>(std::numeric_limits<int>::max()) / N) {
        if (rank == 0) {
            std::fprintf(stderr, "Matrix is too large to gather with MPI_Gatherv.\n");
        }
        MPI_Finalize();
        return 1;
    }

    const size_t ranks = static_cast<size_t>(rankCount);
    const size_t rankIndex = static_cast<size_t>(rank);
    const size_t baseRows = N / ranks;
    const size_t remainder = N % ranks;
    const size_t localRows = baseRows + (rankIndex < remainder ? 1 : 0);
    const size_t firstRow = rankIndex * baseRows + std::min(rankIndex, remainder);

    if (rank == 0) {
        std::printf("Matrix Multiplication Benchmark\n");
        std::printf("Matrix size: %zu x %zu\n", N, N);
        std::printf("MPI ranks: %d\n", rankCount);
        std::printf("Validation: %s\n", validate ? "enabled" : "disabled");
        std::printf("Initializing matrices...\n");
    }

    std::vector<double> localA(localRows * N);
    std::vector<double> B(N * N);
    std::vector<double> localC(localRows * N);
    initLocalMatrix(localA, N, firstRow, localRows);
    // B is deterministic, so parallel construction avoids broadcasting N^2
    // elements and removes a serial/network bottleneck before every run.
    initMatrix(B, N);

    if (rank == 0) {
        std::printf("Computing matrix multiplication...\n");
    }
    MPI_Barrier(MPI_COMM_WORLD);
    const double start = MPI_Wtime();
    matrixMultiplyLocal(localA, B, localC, N, localRows);
    const double localSeconds = MPI_Wtime() - start;

    double seconds = 0.0;
    MPI_Reduce(&localSeconds, &seconds, 1, MPI_DOUBLE, MPI_MAX, 0,
               MPI_COMM_WORLD);

    if (rank == 0) {
        std::printf("Computation time: %.3f ms\n", seconds * 1000.0);
        const double n = static_cast<double>(N);
        const double gflops = (2.0 * n * n * n) / seconds / 1e9;
        std::printf("Performance: %.3f GFLOPS\n", gflops);
    }

    if (printResults) {
        std::vector<int> counts(rankCount);
        std::vector<int> displacements(rankCount);
        for (int r = 0; r < rankCount; ++r) {
            const size_t ri = static_cast<size_t>(r);
            const size_t rows = baseRows + (ri < remainder ? 1 : 0);
            const size_t offset = ri * baseRows + std::min(ri, remainder);
            counts[r] = static_cast<int>(rows * N);
            displacements[r] = static_cast<int>(offset * N);
        }

        std::vector<double> C;
        if (rank == 0) {
            C.resize(N * N);
        }
        MPI_Gatherv(localC.data(), static_cast<int>(localRows * N), MPI_DOUBLE,
                    rank == 0 ? C.data() : nullptr, counts.data(),
                    displacements.data(), MPI_DOUBLE, 0, MPI_COMM_WORLD);
        if (rank == 0) {
            print_results(C, "MatrixC");
        }
    }

    int globallyValid = 1;
    if (validate) {
        if (rank == 0) {
            std::printf("Validating result...\n");
        }
        const int locallyValid =
            validateLocalResult(localA, B, localC, N, firstRow, localRows) ? 1 : 0;
        MPI_Allreduce(&locallyValid, &globallyValid, 1, MPI_INT, MPI_MIN,
                      MPI_COMM_WORLD);
        if (rank == 0) {
            std::printf("Validation: %s\n", globallyValid ? "PASSED" : "FAILED");
        }
    }

    MPI_Finalize();
    return globallyValid ? 0 : 1;
}

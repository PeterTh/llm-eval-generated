#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif
#ifndef M_SQRT_2
#define M_SQRT_2 0.7071067811865475244
#endif
#ifndef M_SQRT1_2
#define M_SQRT1_2 0.7071067811865475244
#endif
#ifndef M_1_SQRTPI
#define M_1_SQRTPI 0.564189583547756286948
#endif

enum OptionType {
    CALL = 0,
    PUT = 1
};

struct OptionInput {
    int type;           // CALL or PUT
    double strike;      // Strike price
    double spot;        // Spot price
    double q;           // Dividend yield
    double r;           // Risk-free rate
    double t;           // Time to maturity
    double vol;         // Volatility
    double value;       // Expected value (for validation)
    double tol;         // Tolerance
};

// Standard normal cumulative distribution function
inline double cumulativeNormal(const double x) noexcept {
    return 0.5 * (1.0 + std::erf(x * M_SQRT1_2));
}

// Standard normal probability density function
inline double normalPDF(const double x) noexcept {
    return M_1_SQRTPI * M_SQRT1_2 * exp(-0.5 * x * x);
}

// Black-Scholes formula for European options
double blackScholes(const OptionInput& option) noexcept {
    const double S = option.spot;
    const double K = option.strike;
    const double r = option.r;
    const double q = option.q;
    const double T = option.t;
    const double sigma = option.vol;
    
    if (T <= 0.0 || sigma <= 0.0) {
        return 0.0;
    }
    
    const double d1 = (log(S / K) + (r - q + 0.5 * sigma * sigma) * T) / (sigma * sqrt(T));
    const double d2 = d1 - sigma * sqrt(T);
    
    const double Nd1 = cumulativeNormal(d1);
    const double Nd2 = cumulativeNormal(d2);
    const double discount = exp(-r * T);
    
    double price;
    if (option.type == CALL) {
        price = S * exp(-q * T) * Nd1 - K * discount * Nd2;
    } else { // PUT
        price = K * discount * cumulativeNormal(-d2) - S * exp(-q * T) * cumulativeNormal(-d1);
    }
    
    return price;
}

// Standard test cases for validation
inline constexpr std::array<OptionInput, 7> getTestOptions() noexcept {
    return {{
        {CALL, 40.00, 42.00, 0.04, 0.08, 0.75, 0.35, 5.0975, 1.0e-3},
        {CALL, 100.00, 90.00, 0.10, 0.10, 0.10, 0.15, 0.0205, 1.0e-3},
        {CALL, 100.00, 100.00, 0.10, 0.10, 0.10, 0.15, 1.8734, 1.0e-3},
        {CALL, 100.00, 110.00, 0.10, 0.10, 0.10, 0.15, 9.9413, 1.0e-3},
        {PUT, 100.00, 90.00, 0.10, 0.10, 0.10, 0.15, 9.9210, 1.0e-3},
        {PUT, 100.00, 100.00, 0.10, 0.10, 0.10, 0.15, 1.8734, 1.0e-3},
        {PUT, 100.00, 110.00, 0.10, 0.10, 0.10, 0.15, 0.0408, 1.0e-3},
    }};
}

// Generate a contiguous global range of options by scaling the test set.
// Using global indices keeps each rank's input bit-for-bit identical to the
// corresponding input generated by the original serial implementation.
void generateOptions(std::vector<OptionInput>& options,
                     const size_t globalBegin,
                     const size_t numOptions) {
    constexpr auto testOptions = getTestOptions();
    options.resize(numOptions);
    
    for (size_t i = 0; i < numOptions; ++i) {
        // Cycle through test options and vary parameters slightly
        const size_t globalIndex = globalBegin + i;
        const OptionInput& base = testOptions[globalIndex % testOptions.size()];
        options[i] = base;
        
        // Add some variation for larger datasets
        const double factor = 1.0 + 0.1 *
            (globalIndex / static_cast<double>(testOptions.size()));
        options[i].spot *= factor;
        options[i].strike *= factor;
    }
}

struct WorkPartition {
    size_t begin;
    size_t count;
};

// A balanced block distribution minimizes communication and keeps the output
// ordering deterministic.  The first remainder ranks receive one extra item.
WorkPartition partitionWork(const size_t total,
                            const int rank,
                            const int numRanks) noexcept {
    const size_t ranks = static_cast<size_t>(numRanks);
    const size_t baseCount = total / ranks;
    const size_t remainder = total % ranks;
    const size_t rankIndex = static_cast<size_t>(rank);
    const size_t count = baseCount + (rankIndex < remainder ? 1 : 0);
    const size_t begin = rankIndex * baseCount +
        std::min(rankIndex, remainder);
    return {begin, count};
}

// Collect a global contiguous range into the matching portion of rootResults.
// MPI_Gatherv uses int counts/displacements, so large diagnostic output is
// transferred in bounded chunks by the caller.
void gatherResultRange(const std::vector<double>& localResults,
                       const WorkPartition& localWork,
                       const size_t totalOptions,
                       const size_t rangeBegin,
                       const size_t rangeCount,
                       std::vector<double>* rootResults,
                       const size_t rootOffset,
                       const int rank,
                       const int numRanks) {
    std::vector<int> receiveCounts(static_cast<size_t>(numRanks), 0);
    std::vector<int> displacements(static_cast<size_t>(numRanks), 0);

    const size_t rangeEnd = rangeBegin + rangeCount;
    const size_t localEnd = localWork.begin + localWork.count;
    const size_t sendBegin = std::max(rangeBegin, localWork.begin);
    const size_t sendEnd = std::min(rangeEnd, localEnd);
    const size_t sendCount = sendEnd > sendBegin ? sendEnd - sendBegin : 0;

    if (rank == 0) {
        for (int process = 0; process < numRanks; ++process) {
            const WorkPartition processWork =
                partitionWork(totalOptions, process, numRanks);
            const size_t processEnd = processWork.begin + processWork.count;
            const size_t receiveBegin = std::max(rangeBegin, processWork.begin);
            const size_t receiveEnd = std::min(rangeEnd, processEnd);
            const size_t receiveCount = receiveEnd > receiveBegin
                ? receiveEnd - receiveBegin : 0;

            receiveCounts[static_cast<size_t>(process)] =
                static_cast<int>(receiveCount);
            displacements[static_cast<size_t>(process)] =
                static_cast<int>(receiveBegin - rangeBegin);
        }
    }

    static const double emptyValue = 0.0;
    const double* sendBuffer = sendCount != 0
        ? localResults.data() + (sendBegin - localWork.begin)
        : &emptyValue;
    double* receiveBuffer = rank == 0 && rangeCount != 0
        ? rootResults->data() + rootOffset
        : nullptr;

    MPI_Gatherv(sendBuffer, static_cast<int>(sendCount), MPI_DOUBLE,
                receiveBuffer, receiveCounts.data(), displacements.data(),
                MPI_DOUBLE, 0, MPI_COMM_WORLD);
}

bool validateResults(const std::vector<OptionInput>& options, 
                     const std::vector<double>& results) {
    bool allPassed = true;
    const int numChecks = std::min(static_cast<size_t>(10), options.size());
    
    printf("Checking computed option prices:\n");
    for (int i = 0; i < numChecks; ++i) {
        const double computed = results[i];
        const double expected = options[i].value;
        const double error = fabs(computed - expected);
        const double relError = error / (fabs(expected) + 1e-10);
        
        printf("  Option %d: computed=%.4f, expected=%.4f, rel_error=%.4e\n", 
               i, computed, expected, relError);
        
        // Relaxed validation - just check values are positive and reasonable
        if (computed < 0.0 || computed > 1000.0 || std::isnan(computed) || std::isinf(computed)) {
            printf("Validation failed at option %d: invalid value %.4f\n", i, computed);
            allPassed = false;
        }
    }
    
    return allPassed;
}

void printUsage(const char* progName) {
    printf("Usage: %s [options]\n", progName);
    printf("Options:\n");
    printf("  -n <num>     Number of options to price (default: 10000)\n");
    printf("  -v           Enable validation against known values\n");
    printf("  -r           Print results for external validation\n");
    printf("  -h           Show this help message\n");
}

int main(int argc, char** argv) {
    if (MPI_Init(&argc, &argv) != MPI_SUCCESS) {
        return 1;
    }

    int rank = 0;
    int numRanks = 1;
    MPI_Comm_rank(MPI_COMM_WORLD, &rank);
    MPI_Comm_size(MPI_COMM_WORLD, &numRanks);

    size_t numOptions = 10000;
    bool validate = false;
    bool printResults = false;
    int argumentStatus = 0;
    
    // Parse command line arguments
    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "-n") == 0 && i + 1 < argc) {
            numOptions = atoll(argv[++i]);
        } else if (strcmp(argv[i], "-v") == 0) {
            validate = true;
        } else if (strcmp(argv[i], "-r") == 0) {
            printResults = true;
        } else if (strcmp(argv[i], "-h") == 0) {
            if (rank == 0) {
                printUsage(argv[0]);
            }
            MPI_Finalize();
            return 0;
        } else {
            if (rank == 0) {
                printf("Unknown option: %s\n", argv[i]);
                printUsage(argv[0]);
            }
            argumentStatus = 1;
            break;
        }
    }

    if (argumentStatus != 0) {
        MPI_Finalize();
        return argumentStatus;
    }
    
    if (rank == 0) {
        printf("Black-Scholes Option Pricing Benchmark\n");
        printf("Number of options: %zu\n", numOptions);
        printf("Validation: %s\n", validate ? "enabled" : "disabled");
    }
    
    // Generate only the rank-local input block.  Inputs are generated before
    // timing, as in the serial benchmark.
    const WorkPartition localWork = partitionWork(numOptions, rank, numRanks);
    std::vector<OptionInput> options;
    generateOptions(options, localWork.begin, localWork.count);
    
    std::vector<double> localResults(localWork.count);
    
    // Synchronize the start and report the slowest rank's compute time.  This
    // is the distributed execution time seen by the application.
    if (rank == 0) {
        printf("Pricing options...\n");
    }
    MPI_Barrier(MPI_COMM_WORLD);
    const double start = MPI_Wtime();
    
    for (size_t i = 0; i < localWork.count; ++i) {
        localResults[i] = blackScholes(options[i]);
    }
    
    const double localDuration = MPI_Wtime() - start;
    double duration = 0.0;
    MPI_Reduce(&localDuration, &duration, 1, MPI_DOUBLE, MPI_MAX, 0,
               MPI_COMM_WORLD);
    
    if (rank == 0) {
        printf("Computation time: %.3f ms\n", duration * 1000.0);
        printf("Options per second: %.0f\n", numOptions / duration);
    }

    std::vector<double> globalResults;
    
    // Diagnostic output needs the serial global order, but the hot path has
    // no communication beyond the timing reduction.  MPI_Gatherv is limited
    // to int counts, so gather a bounded range per collective.
    if (printResults) {
        if (rank == 0) {
            globalResults.resize(numOptions);
        }

        constexpr size_t maxGatherElements = static_cast<size_t>(INT_MAX);
        for (size_t rangeBegin = 0; rangeBegin < numOptions;) {
            const size_t rangeCount = std::min(maxGatherElements,
                numOptions - rangeBegin);
            gatherResultRange(localResults, localWork, numOptions,
                              rangeBegin, rangeCount, &globalResults,
                              rangeBegin, rank, numRanks);
            rangeBegin += rangeCount;
        }

        if (rank == 0) {
            print_results(globalResults, "OptionPrices");
        }
    }
    
    // Validation
    int exitCode = 0;
    if (validate) {
        constexpr size_t validationCount = 10;
        const size_t numChecks = std::min(validationCount, numOptions);
        std::vector<double> validationResults(numChecks);

        if (printResults) {
            if (rank == 0) {
                std::copy_n(globalResults.begin(), numChecks,
                            validationResults.begin());
            }
        } else if (numChecks != 0) {
            gatherResultRange(localResults, localWork, numOptions, 0,
                              numChecks, &validationResults, 0, rank,
                              numRanks);
        }

        if (rank == 0) {
            std::vector<OptionInput> validationOptions;
            generateOptions(validationOptions, 0, numChecks);
            printf("Validating results...\n");
            const bool valid = validateResults(validationOptions,
                                               validationResults);
            printf("Validation: %s\n", valid ? "PASSED" : "FAILED");
            exitCode = valid ? 0 : 1;
        }

        MPI_Bcast(&exitCode, 1, MPI_INT, 0, MPI_COMM_WORLD);
    }
    
    MPI_Finalize();
    return exitCode;
}

// A square 2-D block-cyclic distribution gives every process a comparable
// amount of work and keeps the distributed factor at O(n^2 / P) storage.  A
// tile is deliberately large enough to make the local rank-k updates compute
// intensive, while still exposing enough tiles for the process grid.
constexpr int kTileSize = 128;

// Generate the same symmetric positive definite matrix as the original
// benchmark.  The matrix is generated by rank zero and distributed before
// timing the factorization; this retains the benchmark's input semantics
// without replicating the working matrix on every process.
void generatePositiveDefiniteMatrix(std::vector<double>& A, const size_t n) {
    std::vector<double> B(n * n);
    unsigned int seed = 42;

    for (size_t i = 0; i < n * n; ++i) {
        B[i] = (rand_r(&seed) / (double)RAND_MAX) - 0.5;
    }

    for (size_t i = 0; i < n; ++i) {
        for (size_t j = 0; j < n; ++j) {
            double sum = 0.0;
            for (size_t k = 0; k < n; ++k) {
                sum += B[i * n + k] * B[j * n + k];
            }
            A[i * n + j] = sum;
        }
    }

    for (size_t i = 0; i < n; ++i) {
        A[i * n + i] += n;
    }
}

bool validateCholesky(const std::vector<double>& L,
                      const std::vector<double>& A_orig,
                      const size_t n) {
    std::vector<double> reconstructed(n * n);

    for (size_t i = 0; i < n; ++i) {
        for (size_t j = 0; j < n; ++j) {
            double sum = 0.0;
            for (size_t k = 0; k < n; ++k) {
                sum += L[i * n + k] * L[j * n + k];
            }
            reconstructed[i * n + j] = sum;
        }
    }

    double maxError = 0.0;
    double relError = 0.0;

    for (size_t i = 0; i < n * n; ++i) {
        const double error = fabs(reconstructed[i] - A_orig[i]);
        maxError = std::max(maxError, error);

        const double rel = error / (fabs(A_orig[i]) + 1e-10);
        relError = std::max(relError, rel);
    }

    printf("Max absolute error: %.10e\n", maxError);
    printf("Max relative error: %.10e\n", relError);

    if (relError > 1e-6) {
        printf("Validation failed: relative error too large\n");
        return false;
    }

    return true;
}

struct DistributedMatrix {
    size_t n = 0;
    int tile_size = 0;
    int tile_count = 0;
    int process_rows = 0;
    int process_cols = 0;
    int my_row = 0;
    int my_col = 0;
    size_t local_tile_rows = 0;
    size_t local_tile_cols = 0;
    size_t tile_elements = 0;
    std::vector<double> values;

    DistributedMatrix() = default;

    DistributedMatrix(const size_t matrix_size,
                      const int block_size,
                      const int grid_rows,
                      const int grid_cols,
                      const int process_row,
                      const int process_col)
        : n(matrix_size),
          tile_size(block_size),
          process_rows(grid_rows),
          process_cols(grid_cols),
          my_row(process_row),
          my_col(process_col),
          tile_elements(static_cast<size_t>(block_size) * block_size) {
        const size_t tile_count_size = (n + tile_size - 1) / tile_size;
        tile_count = static_cast<int>(tile_count_size);
        local_tile_rows = tile_count <= my_row
                              ? 0
                              : 1 + static_cast<size_t>(tile_count - 1 - my_row) /
                                    process_rows;
        local_tile_cols = tile_count <= my_col
                              ? 0
                              : 1 + static_cast<size_t>(tile_count - 1 - my_col) /
                                    process_cols;
        values.resize(local_tile_rows * local_tile_cols * tile_elements, 0.0);
    }

    size_t tileRows(const int tile_row) const {
        const size_t first = static_cast<size_t>(tile_row) * tile_size;
        return std::min(static_cast<size_t>(tile_size), n - first);
    }

    size_t tileCols(const int tile_col) const {
        const size_t first = static_cast<size_t>(tile_col) * tile_size;
        return std::min(static_cast<size_t>(tile_size), n - first);
    }

    double* tile(const int tile_row, const int tile_col) {
        const size_t local_row =
            static_cast<size_t>(tile_row - my_row) / process_rows;
        const size_t local_col =
            static_cast<size_t>(tile_col - my_col) / process_cols;
        const size_t offset =
            (local_row * local_tile_cols + local_col) * tile_elements;
        return values.data() + offset;
    }

    const double* tile(const int tile_row, const int tile_col) const {
        const size_t local_row =
            static_cast<size_t>(tile_row - my_row) / process_rows;
        const size_t local_col =
            static_cast<size_t>(tile_col - my_col) / process_cols;
        const size_t offset =
            (local_row * local_tile_cols + local_col) * tile_elements;
        return values.data() + offset;
    }
};

int mpiCount(const size_t count) {
    if (count > static_cast<size_t>(std::numeric_limits<int>::max())) {
        fprintf(stderr, "MPI message is too large for the MPI count interface\n");
        MPI_Abort(MPI_COMM_WORLD, 1);
    }
    return static_cast<int>(count);
}

void packFromGlobal(const std::vector<double>& global,
                    DistributedMatrix& local) {
    std::fill(local.values.begin(), local.values.end(), 0.0);

    for (int tile_row = local.my_row; tile_row < local.tile_count;
         tile_row += local.process_rows) {
        const size_t rows = local.tileRows(tile_row);
        for (int tile_col = local.my_col; tile_col < local.tile_count;
             tile_col += local.process_cols) {
            if (tile_row < tile_col) {
                continue;
            }

            const size_t cols = local.tileCols(tile_col);
            double* destination = local.tile(tile_row, tile_col);
            for (size_t row = 0; row < rows; ++row) {
                const size_t global_row =
                    static_cast<size_t>(tile_row) * local.tile_size + row;
                for (size_t col = 0; col < cols; ++col) {
                    const size_t global_col =
                        static_cast<size_t>(tile_col) * local.tile_size + col;
                    destination[row * local.tile_size + col] =
                        global[global_row * local.n + global_col];
                }
            }
        }
    }
}

void unpackToGlobal(const DistributedMatrix& local,
                    std::vector<double>& global) {
    for (int tile_row = local.my_row; tile_row < local.tile_count;
         tile_row += local.process_rows) {
        const size_t rows = local.tileRows(tile_row);
        for (int tile_col = local.my_col; tile_col < local.tile_count;
             tile_col += local.process_cols) {
            if (tile_row < tile_col) {
                continue;
            }

            const size_t cols = local.tileCols(tile_col);
            const double* source = local.tile(tile_row, tile_col);
            for (size_t row = 0; row < rows; ++row) {
                const size_t global_row =
                    static_cast<size_t>(tile_row) * local.tile_size + row;
                for (size_t col = 0; col < cols; ++col) {
                    const size_t global_col =
                        static_cast<size_t>(tile_col) * local.tile_size + col;
                    global[global_row * local.n + global_col] =
                        source[row * local.tile_size + col];
                }
            }
        }
    }
}

void distributeInitialMatrix(const std::vector<double>& global,
                             DistributedMatrix& local,
                             MPI_Comm cartesian,
                             const int rank,
                             const int root) {
    const int count = mpiCount(local.values.size());

    if (rank == root) {
        for (int destination_rank = 0; destination_rank < local.process_rows * local.process_cols;
             ++destination_rank) {
            int coordinates[2] = {0, 0};
            MPI_Cart_coords(cartesian, destination_rank, 2, coordinates);
            DistributedMatrix destination(local.n,
                                          local.tile_size,
                                          local.process_rows,
                                          local.process_cols,
                                          coordinates[0],
                                          coordinates[1]);
            packFromGlobal(global, destination);

            const int destination_count = mpiCount(destination.values.size());
            if (destination_rank == root) {
                local.values.swap(destination.values);
            } else {
                MPI_Send(destination.values.data(),
                         destination_count,
                         MPI_DOUBLE,
                         destination_rank,
                         100,
                         cartesian);
            }
        }
    } else {
        MPI_Recv(local.values.data(),
                 count,
                 MPI_DOUBLE,
                 root,
                 100,
                 cartesian,
                 MPI_STATUS_IGNORE);
    }

    MPI_Barrier(cartesian);
}

void factorDiagonal(double* diagonal,
                    const size_t block_size,
                    const int leading_dimension,
                    bool& success) {
    success = true;

    for (size_t row = 0; row < block_size; ++row) {
        for (size_t col = 0; col <= row; ++col) {
            double sum = 0.0;
            for (size_t k = 0; k < col; ++k) {
                sum += diagonal[row * leading_dimension + k] *
                       diagonal[col * leading_dimension + k];
            }

            if (row == col) {
                const double value =
                    diagonal[row * leading_dimension + col] - sum;
                if (value <= 0.0) {
                    success = false;
                    return;
                }
                diagonal[row * leading_dimension + col] = sqrt(value);
            } else {
                diagonal[row * leading_dimension + col] =
                    (diagonal[row * leading_dimension + col] - sum) /
                    diagonal[col * leading_dimension + col];
            }
        }

        for (size_t col = row + 1; col < static_cast<size_t>(leading_dimension);
             ++col) {
            diagonal[row * leading_dimension + col] = 0.0;
        }
    }
}

// Solve X * L^T = B for each row of B.  L is lower triangular and both B and
// L are stored row-major with a fixed tile leading dimension.
void triangularSolve(double* panel_tile,
                     const double* diagonal,
                     const size_t rows,
                     const size_t columns,
                     const int leading_dimension) {
    for (size_t row = 0; row < rows; ++row) {
        for (size_t col = 0; col < columns; ++col) {
            double value = panel_tile[row * leading_dimension + col];
            for (size_t k = 0; k < col; ++k) {
                value -= panel_tile[row * leading_dimension + k] *
                         diagonal[col * leading_dimension + k];
            }
            panel_tile[row * leading_dimension + col] =
                value / diagonal[col * leading_dimension + col];
        }
        for (size_t col = columns; col < static_cast<size_t>(leading_dimension);
             ++col) {
            panel_tile[row * leading_dimension + col] = 0.0;
        }
    }
}

// C -= A * B^T.  A and B are transposed panel tiles, so the innermost loop
// operates on contiguous data in both the update tile and B.  This gives the
// compiler a simple SIMD-friendly kernel without requiring a BLAS dependency.
void rankKUpdate(double* C,
                 const double* A_transposed,
                 const double* B_transposed,
                 const size_t rows,
                 const size_t columns,
                 const size_t inner,
                 const int leading_dimension) {
    for (size_t k = 0; k < inner; ++k) {
        const double* a = A_transposed + k * leading_dimension;
        const double* b = B_transposed + k * leading_dimension;
        for (size_t row = 0; row < rows; ++row) {
            double* c = C + row * leading_dimension;
            const double scalar = a[row];
#if defined(__GNUC__) || defined(__clang__)
#pragma GCC ivdep
#endif
            for (size_t col = 0; col < columns; ++col) {
                c[col] -= scalar * b[col];
            }
        }
    }
}

bool choleskyDecomposition(DistributedMatrix& matrix,
                           MPI_Comm cartesian,
                           MPI_Comm row_communicator,
                           MPI_Comm column_communicator,
                           const int rank) {
    const int tile_count = matrix.tile_count;
    const int leading_dimension = matrix.tile_size;
    const size_t tile_elements = matrix.tile_elements;

    std::vector<double> diagonal(tile_elements, 0.0);
    const size_t max_panel_tiles =
        tile_count == 0
            ? 0
            : (static_cast<size_t>(tile_count) + matrix.process_rows - 1) /
                  matrix.process_rows;
    std::vector<double> row_panel(std::max<size_t>(1, max_panel_tiles * tile_elements),
                                  0.0);
    std::vector<double> panel(std::max<size_t>(1,
                                               static_cast<size_t>(tile_count) *
                                                   tile_elements),
                              0.0);
    std::vector<int> panel_counts(matrix.process_rows, 0);
    std::vector<int> panel_displacements(matrix.process_rows, 0);
    std::vector<int> panel_offsets(tile_count, 0);

    for (int k = 0; k < tile_count; ++k) {
        const int diagonal_coordinates[2] = {
            k % matrix.process_rows, k % matrix.process_cols};
        int diagonal_owner = 0;
        MPI_Cart_rank(cartesian, diagonal_coordinates, &diagonal_owner);

        int factor_ok = 1;
        if (rank == diagonal_owner) {
            const size_t block_size = matrix.tileRows(k);
            bool local_ok = true;
            factorDiagonal(matrix.tile(k, k),
                           block_size,
                           leading_dimension,
                           local_ok);
            factor_ok = local_ok ? 1 : 0;
            if (!local_ok) {
                printf("Error: Matrix is not positive definite at diagonal element %zu\n",
                       static_cast<size_t>(k) * matrix.tile_size);
            }
        }
        MPI_Bcast(&factor_ok, 1, MPI_INT, diagonal_owner, cartesian);
        if (factor_ok == 0) {
            return false;
        }

        if (rank == diagonal_owner) {
            std::copy(matrix.tile(k, k),
                      matrix.tile(k, k) + tile_elements,
                      diagonal.begin());
        }

        // Every owner of a tile in block column k needs L(k,k).  Only the
        // process column containing the diagonal participates in this
        // broadcast.
        if (matrix.my_col == k % matrix.process_cols) {
            MPI_Bcast(diagonal.data(),
                      mpiCount(tile_elements),
                      MPI_DOUBLE,
                      k % matrix.process_rows,
                      column_communicator);

            for (int tile_row = k + 1; tile_row < tile_count; ++tile_row) {
                if (tile_row % matrix.process_rows != matrix.my_row) {
                    continue;
                }
                triangularSolve(matrix.tile(tile_row, k),
                                diagonal.data(),
                                matrix.tileRows(tile_row),
                                matrix.tileCols(k),
                                leading_dimension);
            }
        }

        int total_panel_doubles = 0;
        for (int process_row = 0; process_row < matrix.process_rows;
             ++process_row) {
            panel_displacements[process_row] = total_panel_doubles;
            int row_tile_count = 0;
            for (int tile_row = k + 1; tile_row < tile_count; ++tile_row) {
                if (tile_row % matrix.process_rows == process_row) {
                    panel_offsets[tile_row] =
                        total_panel_doubles + row_tile_count *
                                                     mpiCount(tile_elements);
                    ++row_tile_count;
                }
            }
            panel_counts[process_row] = row_tile_count * mpiCount(tile_elements);
            total_panel_doubles += panel_counts[process_row];
        }

        std::fill(row_panel.begin(), row_panel.end(), 0.0);
        if (matrix.my_col == k % matrix.process_cols) {
            int row_tile_number = 0;
            for (int tile_row = k + 1; tile_row < tile_count; ++tile_row) {
                if (tile_row % matrix.process_rows != matrix.my_row) {
                    continue;
                }

                const size_t rows = matrix.tileRows(tile_row);
                const size_t columns = matrix.tileCols(k);
                const double* source = matrix.tile(tile_row, k);
                double* destination =
                    row_panel.data() + row_tile_number * tile_elements;
                for (size_t column = 0; column < columns; ++column) {
                    for (size_t row = 0; row < rows; ++row) {
                        destination[column * leading_dimension + row] =
                            source[row * leading_dimension + column];
                    }
                }
                ++row_tile_number;
            }
        }

        // First make each process row's part of the panel available to every
        // process column, then allgather those parts down each process column.
        // After these two collectives every process owns a read-only copy of
        // the current panel, while the factor itself remains distributed.
        MPI_Bcast(row_panel.data(),
                  panel_counts[matrix.my_row],
                  MPI_DOUBLE,
                  k % matrix.process_cols,
                  row_communicator);
        MPI_Allgatherv(row_panel.data(),
                       panel_counts[matrix.my_row],
                       MPI_DOUBLE,
                       panel.data(),
                       panel_counts.data(),
                       panel_displacements.data(),
                       MPI_DOUBLE,
                       column_communicator);

        for (int tile_row = k + 1; tile_row < tile_count; ++tile_row) {
            if (tile_row % matrix.process_rows != matrix.my_row) {
                continue;
            }

            const size_t rows = matrix.tileRows(tile_row);
            const double* left_panel = panel.data() + panel_offsets[tile_row];
            for (int tile_col = k + 1; tile_col <= tile_row; ++tile_col) {
                if (tile_col % matrix.process_cols != matrix.my_col) {
                    continue;
                }

                rankKUpdate(matrix.tile(tile_row, tile_col),
                            left_panel,
                            panel.data() + panel_offsets[tile_col],
                            rows,
                            matrix.tileCols(tile_col),
                            matrix.tileCols(k),
                            leading_dimension);
            }
        }
    }

    return true;
}

void gatherResult(const DistributedMatrix& local,
                  std::vector<double>& global,
                  MPI_Comm cartesian,
                  const int rank,
                  const int root) {
    const int process_count = local.process_rows * local.process_cols;
    const int local_count = mpiCount(local.values.size());

    if (rank == root) {
        std::fill(global.begin(), global.end(), 0.0);
        unpackToGlobal(local, global);

        for (int source_rank = 0; source_rank < process_count; ++source_rank) {
            if (source_rank == root) {
                continue;
            }

            int coordinates[2] = {0, 0};
            MPI_Cart_coords(cartesian, source_rank, 2, coordinates);
            DistributedMatrix source(local.n,
                                     local.tile_size,
                                     local.process_rows,
                                     local.process_cols,
                                     coordinates[0],
                                     coordinates[1]);
            MPI_Recv(source.values.data(),
                     mpiCount(source.values.size()),
                     MPI_DOUBLE,
                     source_rank,
                     200,
                     cartesian,
                     MPI_STATUS_IGNORE);
            unpackToGlobal(source, global);
        }
    } else {
        MPI_Send(local.values.data(),
                 local_count,
                 MPI_DOUBLE,
                 root,
                 200,
                 cartesian);
    }

    MPI_Barrier(cartesian);
}

void printUsage(const char* progName) {
    printf("Usage: %s [options]\n", progName);
    printf("Options:\n");
    printf("  -n <num>     Matrix size (default: 512)\n");
    printf("  -v           Enable validation\n");
    printf("  -r           Print results for external validation\n");
    printf("  -h           Show this help message\n");
}

bool parseSize(const char* text, size_t& value) {
    char* end = nullptr;
    const unsigned long long parsed = std::strtoull(text, &end, 10);
    if (end == text || *end != '\0' ||
        parsed > static_cast<unsigned long long>(
                     std::numeric_limits<size_t>::max())) {
        return false;
    }
    value = static_cast<size_t>(parsed);
    return true;
}

int main(int argc, char** argv) {
    MPI_Init(&argc, &argv);

    int world_rank = 0;
    int world_size = 0;
    MPI_Comm_rank(MPI_COMM_WORLD, &world_rank);
    MPI_Comm_size(MPI_COMM_WORLD, &world_size);

    size_t n = 512;
    bool validate = false;
    bool printResults = false;
    bool parse_ok = true;

    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "-n") == 0 && i + 1 < argc) {
            parse_ok = parseSize(argv[++i], n);
        } else if (strcmp(argv[i], "-v") == 0) {
            validate = true;
        } else if (strcmp(argv[i], "-r") == 0) {
            printResults = true;
        } else if (strcmp(argv[i], "-h") == 0) {
            if (world_rank == 0) {
                printUsage(argv[0]);
            }
            MPI_Finalize();
            return 0;
        } else {
            if (world_rank == 0) {
                printf("Unknown option: %s\n", argv[i]);
            }
            parse_ok = false;
        }
        if (!parse_ok) {
            break;
        }
    }

    if (!parse_ok) {
        if (world_rank == 0) {
            printUsage(argv[0]);
        }
        MPI_Finalize();
        return 1;
    }

    int dimensions[2] = {0, 0};
    MPI_Dims_create(world_size, 2, dimensions);
    const int periods[2] = {0, 0};
    MPI_Comm cartesian = MPI_COMM_NULL;
    MPI_Cart_create(MPI_COMM_WORLD, 2, dimensions, periods, 0, &cartesian);

    int rank = 0;
    MPI_Comm_rank(cartesian, &rank);
    const int root_coordinates[2] = {0, 0};
    int root = 0;
    MPI_Cart_rank(cartesian, root_coordinates, &root);

    int coordinates[2] = {0, 0};
    MPI_Cart_coords(cartesian, rank, 2, coordinates);
    MPI_Comm row_communicator = MPI_COMM_NULL;
    MPI_Comm column_communicator = MPI_COMM_NULL;
    MPI_Comm_split(cartesian, coordinates[0], coordinates[1], &row_communicator);
    MPI_Comm_split(cartesian, coordinates[1], coordinates[0], &column_communicator);

    if (rank == root) {
        printf("Cholesky Decomposition Benchmark\n");
        printf("Matrix size: %zu x %zu\n", n, n);
        printf("Validation: %s\n", validate ? "enabled" : "disabled");
        printf("MPI processes: %d (%d x %d process grid)\n",
               world_size,
               dimensions[0],
               dimensions[1]);
        printf("Tile size: %d\n", kTileSize);
        printf("Generating positive definite matrix...\n");
        fflush(stdout);
    }

    std::vector<double> global_matrix;
    std::vector<double> original_matrix;
    if (rank == root) {
        global_matrix.resize(n * n);
        generatePositiveDefiniteMatrix(global_matrix, n);
        if (validate) {
            original_matrix = global_matrix;
        }
    }

    DistributedMatrix local_matrix(n,
                                   kTileSize,
                                   dimensions[0],
                                   dimensions[1],
                                   coordinates[0],
                                   coordinates[1]);
    distributeInitialMatrix(global_matrix, local_matrix, cartesian, rank, root);
    if (rank == root) {
        // The factorization and optional result gather use local_matrix.  Do
        // not keep a second full working copy resident on the input root.
        std::vector<double>().swap(global_matrix);
    }

    if (rank == root) {
        printf("Computing Cholesky decomposition...\n");
        fflush(stdout);
    }
    MPI_Barrier(cartesian);
    const double start = MPI_Wtime();
    const bool success = choleskyDecomposition(local_matrix,
                                               cartesian,
                                               row_communicator,
                                               column_communicator,
                                               rank);
    const double end = MPI_Wtime();
    const double local_elapsed = end - start;
    double elapsed = 0.0;
    MPI_Reduce(&local_elapsed,
               &elapsed,
               1,
               MPI_DOUBLE,
               MPI_MAX,
               root,
               cartesian);

    int all_success = success ? 1 : 0;
    MPI_Allreduce(MPI_IN_PLACE, &all_success, 1, MPI_INT, MPI_MIN, cartesian);
    if (all_success == 0) {
        if (rank == root) {
            printf("Cholesky decomposition failed\n");
        }
        MPI_Comm_free(&row_communicator);
        MPI_Comm_free(&column_communicator);
        MPI_Comm_free(&cartesian);
        MPI_Finalize();
        return 1;
    }

    if (rank == root) {
        const long duration_ms = std::max(
            1L, static_cast<long>(std::llround(elapsed * 1000.0)));
        printf("Computation time: %ld ms\n", duration_ms);

        const double ops = static_cast<double>(n) * n * n / 3.0;
        const double gflops = ops / std::max(elapsed, 1.0e-9) / 1.0e9;
        printf("Performance: %.3f GFLOPS\n", gflops);
    }

    std::vector<double> result;
    if (printResults || validate) {
        if (rank == root) {
            result.resize(n * n);
        }
        gatherResult(local_matrix, result, cartesian, rank, root);

        if (rank == root && printResults) {
            print_results(result, "CholeskyL");
        }
    }

    int validation_ok = 1;
    if (validate) {
        if (rank == root) {
            printf("Validating result...\n");
            validation_ok = validateCholesky(result, original_matrix, n) ? 1 : 0;
            printf("Validation: %s\n",
                   validation_ok == 1 ? "PASSED" : "FAILED");
        }
        MPI_Bcast(&validation_ok, 1, MPI_INT, root, cartesian);
    }

    MPI_Comm_free(&row_communicator);
    MPI_Comm_free(&column_communicator);
    MPI_Comm_free(&cartesian);
    MPI_Finalize();
    return validation_ok == 1 ? 0 : 1;
}

// Validate by computing L * L^T and comparing with the original matrix.
bool validateCholesky(const std::vector<double>& L, const std::vector<double>& A_orig,
                      const std::size_t n) {
    std::vector<double> reconstructed(n * n);

    for (std::size_t i = 0; i < n; ++i) {
        for (std::size_t j = 0; j < n; ++j) {
            double sum = 0.0;
            for (std::size_t k = 0; k < n; ++k) {
                sum += L[i * n + k] * L[j * n + k];
            }
            reconstructed[i * n + j] = sum;
        }
    }

    double maxError = 0.0;
    double relError = 0.0;
    for (std::size_t i = 0; i < n * n; ++i) {
        const double error = std::fabs(reconstructed[i] - A_orig[i]);
        maxError = std::max(maxError, error);

        const double relative = error / (std::fabs(A_orig[i]) + 1e-10);
        relError = std::max(relError, relative);
    }

    std::printf("Max absolute error: %.10e\n", maxError);
    std::printf("Max relative error: %.10e\n", relError);

    if (relError > 1e-6) {
        std::printf("Validation failed: relative error too large\n");
        return false;
    }
    return true;
}

int main(int argc, char** argv) {
    MPI_Init(&argc, &argv);

    int rank = 0;
    int process_count = 1;
    MPI_Comm_rank(MPI_COMM_WORLD, &rank);
    MPI_Comm_size(MPI_COMM_WORLD, &process_count);

    std::size_t n = 512;
    bool validate = false;
    bool printResults = false;
    bool parse_ok = true;

    for (int argument = 1; argument < argc; ++argument) {
        if (std::strcmp(argv[argument], "-n") == 0 && argument + 1 < argc) {
            char* end = nullptr;
            const unsigned long long parsed = std::strtoull(argv[++argument], &end, 10);
            if (end == argv[argument] || *end != '\0') {
                parse_ok = false;
            } else {
                n = static_cast<std::size_t>(parsed);
            }
        } else if (std::strcmp(argv[argument], "-v") == 0) {
            validate = true;
        } else if (std::strcmp(argv[argument], "-r") == 0) {
            printResults = true;
        } else if (std::strcmp(argv[argument], "-h") == 0) {
            if (rank == 0) {
                printUsage(argv[0]);
            }
            MPI_Finalize();
            return 0;
        } else {
            parse_ok = false;
        }
    }

    if (!parse_ok) {
        if (rank == 0) {
            std::printf("Invalid command line arguments\n");
            printUsage(argv[0]);
        }
        MPI_Finalize();
        return 1;
    }

    std::vector<std::size_t> row_starts;
    std::vector<std::size_t> row_ends;
    makeRowPartition(n, process_count, row_starts, row_ends);
    const std::size_t row_start = row_starts[static_cast<std::size_t>(rank)];
    const std::size_t local_rows =
        row_ends[static_cast<std::size_t>(rank)] - row_start;

    if (rank == 0) {
        std::printf("Cholesky Decomposition Benchmark\n");
        std::printf("Matrix size: %zu x %zu\n", n, n);
        std::printf("MPI processes: %d\n", process_count);
        std::printf("Validation: %s\n", validate ? "enabled" : "disabled");
        std::printf("Generating positive definite matrix...\n");
    }

    std::vector<double> local_a;
    generatePositiveDefiniteMatrix(local_a, n, row_start, local_rows, row_starts, row_ends,
                                   MPI_COMM_WORLD);

    std::vector<double> local_original;
    if (validate) {
        local_original = local_a;
    }

    if (rank == 0) {
        std::printf("Computing Cholesky decomposition...\n");
    }
    MPI_Barrier(MPI_COMM_WORLD);
    const double start = MPI_Wtime();

    // A tile of 128 doubles gives the panel collectives enough payload to
    // amortize latency while keeping diagonal work cache resident.
    const bool success = choleskyDecomposition(local_a, n, row_start, local_rows, row_starts,
                                               row_ends, MPI_COMM_WORLD, 128);

    const double local_duration = MPI_Wtime() - start;
    double duration = 0.0;
    MPI_Reduce(&local_duration, &duration, 1, MPI_DOUBLE, MPI_MAX, 0, MPI_COMM_WORLD);

    if (!success) {
        if (rank == 0) {
            std::printf("Cholesky decomposition failed\n");
        }
        MPI_Finalize();
        return 1;
    }

    if (rank == 0) {
        const long duration_ms = static_cast<long>(duration * 1000.0);
        std::printf("Computation time: %ld ms\n", duration_ms);

        const double operations = static_cast<double>(n) * static_cast<double>(n) *
                                  static_cast<double>(n) / 3.0;
        const double gflops = duration > 0.0 ? operations / duration / 1e9 : 0.0;
        std::printf("Performance: %.3f GFLOPS\n", gflops);
    }

    std::vector<double> global_a;
    std::vector<double> global_original;
    if (validate || printResults) {
        // Match the original result semantics: upper-triangular output is
        // explicitly zeroed before optional printing or validation.
        for (std::size_t local_row = 0; local_row < local_rows; ++local_row) {
            const std::size_t row = row_start + local_row;
            for (std::size_t column = row + 1; column < n; ++column) {
                local_a[local_row * n + column] = 0.0;
            }
        }

        gatherRows(local_a, global_a, n, row_starts, row_ends, MPI_COMM_WORLD, 0);
        if (validate) {
            gatherRows(local_original, global_original, n, row_starts, row_ends,
                       MPI_COMM_WORLD, 0);
        }
    }

    int validation_ok = 1;
    if (rank == 0 && printResults) {
        print_results(global_a, "CholeskyL");
    }

    if (validate) {
        if (rank == 0) {
            std::printf("Validating result...\n");
            validation_ok = validateCholesky(global_a, global_original, n) ? 1 : 0;
            std::printf("Validation: %s\n", validation_ok ? "PASSED" : "FAILED");
        }
        MPI_Bcast(&validation_ok, 1, MPI_INT, 0, MPI_COMM_WORLD);
    }

    MPI_Finalize();
    return validation_ok == 1 ? 0 : 1;
}

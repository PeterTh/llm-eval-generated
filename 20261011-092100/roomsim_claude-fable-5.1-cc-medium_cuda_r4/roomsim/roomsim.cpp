/**
 * Room Response Simulation Benchmark (CUDA version)
 *
 * Room impulse response simulation using radiosity-based wave propagation.
 * It models how sound/light waves propagate between surfaces in a room by
 * computing:
 *
 * 1. Form factors (Kij) between all pairs of triangles based on visibility and geometry
 * 2. Wave propagation using radiosity equations with time delays (Tau)
 * 3. Distance estimation via cross-correlation of radiosity values
 *
 * The implementation generates a procedural icosphere mesh to simulate a room.
 *
 * Parallelization: all O(N^2) and O(N^2 T) work runs on the GPU.
 *  - Form factors: one thread per (pair, ray); octree visibility queries are
 *    executed with an explicit traversal stack on a flattened octree.
 *  - The sequential program draws all Monte Carlo samples from a single
 *    std::mt19937 stream. That exact stream is reproduced on the GPU: the
 *    index of every random draw is known in advance (64 draws per visible
 *    pair), the stream is split into sub-streams by MT19937 jump-ahead
 *    (polynomial arithmetic over GF(2)), and each sub-stream is generated by a
 *    thread block. The results are therefore sample-for-sample equivalent to
 *    the original implementation.
 *  - Wave propagation: one warp per receiving triangle per timestep.
 *  - Cross-correlation: one block per triangle, one thread per lag.
 */


// Check that q annihilates the MT19937 state sequence: XOR_{k: q_k = 1} seq[k + w] == 0.
static bool annihilatesSequence(const GF2Poly& q, int D) {
    std::vector<int> exps;
    for (int k = 0; k <= D; ++k) if (q.bit(static_cast<size_t>(k))) exps.push_back(k);
    const int blocks = (D + N - 1) / N + 1;
    std::vector<uint32_t> seq(static_cast<size_t>(blocks) * N);
    std::vector<uint32_t> s(N);
    seedState(s.data(), 42u);
    twistHost(s.data());
    for (int b = 0; b < blocks; ++b) {
        std::copy(s.begin(), s.end(), seq.begin() + static_cast<size_t>(b) * N);
        twistHost(s.data());
    }
    for (int w = 0; w < N; ++w) {
        uint32_t acc = 0;
        for (int k : exps) acc ^= seq[static_cast<size_t>(k) + w];
        if (acc) return false;
    }
    return true;
}

// Minimal polynomial q(x) of the MT19937 state transition. Uses the known sparse
// polynomial after verifying it; falls back to recovering it with Berlekamp-Massey.
static GF2Poly transitionPolynomial(int& D) {
    {
        const int deg = Q_EXPONENTS[sizeof(Q_EXPONENTS) / sizeof(Q_EXPONENTS[0]) - 1];
        GF2Poly q(static_cast<size_t>(deg) / 64 + 2);
        for (int e : Q_EXPONENTS) q.w[static_cast<size_t>(e) >> 6] |= 1ull << (e & 63);
        if (annihilatesSequence(q, deg)) {
            D = deg;
            return q;
        }
        fprintf(stderr, "Warning: built-in MT19937 polynomial failed verification; recomputing\n");
    }
    constexpr int DEG = 19938;
    std::vector<uint8_t> seq(2 * DEG + 128);
    std::mt19937 rng(42);
    for (auto& b : seq) b = static_cast<uint8_t>(rng() & 1u);
    int L = 0;
    GF2Poly C = berlekampMassey(seq, L);
    if (L < DEG - 1 || L > DEG || C.degree() != L) {
        fprintf(stderr, "Failed to recover the MT19937 minimal polynomial (degree %d)\n", L);
        exit(1);
    }
    // Berlekamp-Massey yields the connection polynomial C (s_n = sum_{i>=1} C_i s_{n-i});
    // the forward recurrence polynomial is its reciprocal P(x) = x^L C(1/x).
    GF2Poly P(C.w.size());
    for (int i = 0; i <= L; ++i) {
        if (C.bit(static_cast<size_t>(i))) P.w[static_cast<size_t>(L - i) >> 6] |= 1ull << ((L - i) & 63);
    }
    GF2Poly q = P;
    D = L;
    if (P.bit(0)) {   // multiply by x so that q annihilates the full 19968-bit state
        q = GF2Poly(P.w.size());
        xorShifted(q, P, 1, P.w.size() - 1);
        D = L + 1;
    }
    if (!annihilatesSequence(q, D)) {
        fprintf(stderr, "Recovered MT19937 polynomial failed verification\n");
        exit(1);
    }
    return q;
}


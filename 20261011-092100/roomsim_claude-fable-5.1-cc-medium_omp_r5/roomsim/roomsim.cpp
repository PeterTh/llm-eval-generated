/**
 * Room Response Simulation Benchmark
 * 
 * This is a simplified implementation of room impulse response simulation using
 * radiosity-based wave propagation, parallelized for shared-memory multicore
 * CPUs with OpenMP. Results are bit-identical to the sequential reference
 * implementation (the Monte Carlo random stream is reproduced exactly).
 * It models how sound/light waves propagate between surfaces in a room by
 * computing:
 * 
 * 1. Form factors (Kij) between all pairs of triangles based on visibility and geometry
 * 2. Wave propagation using radiosity equations with time delays (Tau)
 * 3. Distance estimation via cross-correlation of radiosity values
 * 
 * The implementation generates a procedural icosphere mesh to simulate a room.
 */


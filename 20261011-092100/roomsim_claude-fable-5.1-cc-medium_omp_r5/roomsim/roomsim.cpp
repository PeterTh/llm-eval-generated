class RandomGenerator {
    std::mt19937 rng;
    std::uniform_real_distribution<val_t> dist;
public:
    explicit RandomGenerator(uint32_t seed = 42) : rng(seed), dist(0.0f, 1.0f) {}
    val_t rand() { return dist(rng); }
    // Skip n draws of the underlying stream. Each rand() consumes exactly one
    // 32-bit engine output (generate_canonical<float,24> with a 32-bit engine),
    // so this advances the stream exactly as n calls to rand() would.
    void discard(unsigned long long n) { rng.discard(n); }
};

// Number of engine draws consumed by rand() per call
constexpr unsigned long long DRAWS_PER_RAND = 1;
// Draws consumed by computeKij for a pair that passes the orientation cull
constexpr unsigned long long DRAWS_PER_PAIR = DRAWS_PER_RAND * 4 * NUM_RAYS;

// ============================================================================
// OpenMP helpers
// ============================================================================

// Team size for light-weight, synchronization-heavy loops: never more threads
// than there are 'grain'-sized pieces of work. Spawning the whole machine for a
// few microseconds of work per barrier only adds scheduling jitter.
int teamSizeForWork(size_t workItems, size_t grain) {
    const int maxThreads = omp_get_max_threads();
    const size_t pieces = std::max<size_t>(1, workItems / grain);
    return static_cast<int>(std::min<size_t>(static_cast<size_t>(maxThreads), pieces));
}

// When the default team would occupy every hardware thread of a large machine,
// leave ~3% of them free. Fully subscribed barriers stall for a whole scheduler
// time slice whenever the OS preempts a single thread, which costs far more
// than the few threads given up.
void configureThreadCount() {
    const int procs = omp_get_num_procs();
    const int requested = omp_get_max_threads();
    if (procs >= 32 && requested >= procs) {
        omp_set_num_threads(procs - procs / 32);
    }
}

inline void cpuRelax() {
#if defined(__x86_64__) || defined(__i386__)
    __builtin_ia32_pause();
#endif
}

// Allocator that leaves trivially-constructible elements uninitialized on
// resize(), so large matrices can be first-touched (and thus placed in memory)
// by the threads that later work on them instead of by the main thread.
template <typename T>
struct DefaultInitAllocator : std::allocator<T> {
    template <typename U> struct rebind { using other = DefaultInitAllocator<U>; };
    using std::allocator<T>::allocator;
    template <typename U>
    void construct(U* p) noexcept(std::is_nothrow_default_constructible<U>::value) {
        ::new (static_cast<void*>(p)) U;
    }
    template <typename U, typename... Args>
    void construct(U* p, Args&&... args) {
        ::new (static_cast<void*>(p)) U(std::forward<Args>(args)...);
    }
};

// Generate a random point inside a triangle using barycentric coordinates
Vec3 randomPointInTriangle(const Triangle& t, RandomGenerator& rng) {
    val_t u = rng.rand();
    val_t v = rng.rand();
    if (u + v > 1.0f) {
        u = 1.0f - u;
        v = 1.0f - v;
    }
    Vec3 ab = t.b - t.a;
    Vec3 ac = t.c - t.a;
    return t.a + ab * u + ac * v;
}

// ============================================================================
// Ray-Triangle Intersection (Möller-Trumbore algorithm)
// ============================================================================

val_t rayTriangleIntersect(const Vec3& orig, const Vec3& dir,
                            const Vec3& v0, const Vec3& v1, const Vec3& v2) {
    Vec3 e1 = v1 - v0;
    Vec3 e2 = v2 - v0;
    Vec3 pvec = dir.cross(e2);
    val_t det = e1.dot(pvec);

    if (std::abs(det) < EPSILON) return std::numeric_limits<val_t>::max();

    val_t invDet = 1.0f / det;
    Vec3 tvec = orig - v0;
    val_t u = tvec.dot(pvec) * invDet;
    if (u < 0.0f || u > 1.0f) return std::numeric_limits<val_t>::max();

    Vec3 qvec = tvec.cross(e1);
    val_t v = dir.dot(qvec) * invDet;
    if (v < 0.0f || u + v > 1.0f) return std::numeric_limits<val_t>::max();

    return e2.dot(qvec) * invDet;
}

// ============================================================================
// Visibility Testing (Octree-accelerated)
// ============================================================================

// Check if a ray between two triangles is blocked by any other triangle
// Uses octree for O(log N) instead of O(N) search
bool isRayBlocked(const Vec3& from, const Vec3& to,
                  const Octree& octree,
                  size_t srcTriIdx, size_t dstTriIdx) {
    Vec3 dir = to - from;
    val_t rayLen = dir.norm();
    if (rayLen < EPSILON) return true;
    Vec3 dirNorm = dir / rayLen;

    return octree.applyToTris(from, to, [&](size_t idx, const Triangle& tri) {
        if (idx == srcTriIdx || idx == dstTriIdx) return false;

        val_t dist = rayTriangleIntersect(from, dirNorm, tri.a, tri.b, tri.c);
        if (dist > EPSILON && dist < rayLen - EPSILON) {
            return true;  // Ray is blocked
        }
        return false;
    });
}

// ============================================================================
// Form Factor Computation (Kij)
// ============================================================================

// Compute the cosine of angle between vector and triangle normal
val_t cosPhi(const Vec3& v, const Vec3& normal) {
    val_t vNorm = v.norm();
    if (vNorm <= EPSILON) return ZERO;
    return std::max(ZERO, v.dot(normal) / vNorm);
}

// Orientation cull: triangles facing the same direction exchange no energy.
// Kept out-of-line so that the draw-count pass and the kernel evaluate exactly
// the same floating-point code (the cull decides how many RNG draws a pair uses).
__attribute__((noinline))
bool cullSameDirection(const Triangle& triI, const Triangle& triJ) {
    return triI.normal().dot(triJ.normal()) > 0.99f;
}

// Compute form factor Kij between triangle i (receiver) and triangle j (emitter)
val_t computeKij(size_t idxI, size_t idxJ,
                  const std::vector<Triangle>& triangles,
                  const Octree& octree,
                  RandomGenerator& rng) {
    const Triangle& triI = triangles[idxI];
    const Triangle& triJ = triangles[idxJ];

    // Cull triangles facing the same direction
    if (cullSameDirection(triI, triJ)) return ZERO;

    val_t kij = ZERO;

    for (int r = 0; r < NUM_RAYS; ++r) {
        Vec3 pI = randomPointInTriangle(triI, rng);
        Vec3 pJ = randomPointInTriangle(triJ, rng);

        if (isRayBlocked(pI, pJ, octree, idxI, idxJ)) continue;

        Vec3 v = pJ - pI;
        val_t distSqr = v.squaredNorm();
        if (distSqr < EPSILON) continue;

        val_t cosPhiI = cosPhi(v, triI.normal());
        val_t cosPhiJ = cosPhi(-v, triJ.normal());

        if (cosPhiI <= ZERO || cosPhiJ <= ZERO) continue;

        kij += (cosPhiI * cosPhiJ) / (PI * distSqr);
    }

    return kij * INV_NUM_RAYS;
}

// ============================================================================
// Tau (time delay) Computation
// ============================================================================

int computeTau(const Triangle& triI, const Triangle& triJ) {
    val_t dist = (triI.center() - triJ.center()).norm();
    return static_cast<int>(std::ceil(dist * INV_WAVE_SPEED));
}

// ============================================================================
// Room Response Simulation State
// ============================================================================

struct SimulationState {
    size_t numTriangles;
    size_t numTimesteps;

    std::vector<Triangle> triangles;
    std::vector<val_t> areas;       // Area of each triangle
    std::vector<val_t> rho;         // Reflectivity (0.0 to 1.0)
    std::vector<val_t, DefaultInitAllocator<val_t>> kij;  // Form factors (N x N matrix, row-major)
    std::vector<int, DefaultInitAllocator<int>> tau;      // Time delays (N x N matrix, row-major)
    std::vector<val_t> radE;        // Emission radiosity (T x N matrix)
    std::vector<val_t> radB;        // Reflected radiosity (T x N matrix)
    std::vector<val_t> distances;   // Computed distances from source

    Octree octree;                  // Spatial acceleration structure

    size_t sourceIndex;
    int simThreads;                 // Team size used for row-partitioned N x N sweeps
    int minTau;                     // Smallest off-diagonal time delay

    size_t idx2d(size_t i, size_t j) const { return i * numTriangles + j; }
    size_t idxTN(size_t t, size_t n) const { return t * numTriangles + n; }
};

// ============================================================================
// Initialization
// ============================================================================

void initializeSimulation(SimulationState& state, int subdivisions, size_t timesteps,
                          size_t sourceIdx, val_t reflectivity) {
    // Generate mesh
    IcosphereMesh mesh(subdivisions, 10.0f);  // Radius 10 units
    state.triangles = std::move(mesh.triangles);
    state.numTriangles = state.triangles.size();
    state.numTimesteps = timesteps;
    state.sourceIndex = sourceIdx % state.numTriangles;

    printf("Generated icosphere mesh with %zu triangles\n", state.numTriangles);

    // Build octree for spatial acceleration
    printf("Building octree...\n");
    state.octree.build(state.triangles);

    // Initialize reflectivity
    state.rho.resize(state.numTriangles, reflectivity);

    // Initialize matrices. The N x N matrices are zeroed in parallel with the
    // same static row partition the simulation sweep uses, so that each page
    // is first touched (and NUMA-placed) by the thread that will read it.
    const size_t N = state.numTriangles;
    state.simThreads = teamSizeForWork(N * N, 16384);
    state.kij.resize(N * N);
    state.tau.resize(N * N);
    #pragma omp parallel for schedule(static) num_threads(state.simThreads)
    for (size_t i = 0; i < N; ++i) {
        std::fill_n(state.kij.data() + i * N, N, ZERO);
        std::fill_n(state.tau.data() + i * N, N, 0);
    }

    // Initialize areas (last parallel region before timing starts, run with the
    // full team so the thread pool is up and warm)
    state.areas.resize(state.numTriangles);
    #pragma omp parallel for schedule(static)
    for (size_t i = 0; i < state.numTriangles; ++i) {
        state.areas[i] = state.triangles[i].area();
    }

    state.radE.resize(timesteps * state.numTriangles, ZERO);
    state.radB.resize(timesteps * state.numTriangles, ZERO);
    state.distances.resize(state.numTriangles, ZERO);

    // Set source emission (active for first half of timesteps)
    size_t timeOn = 0;
    size_t timeOff = timesteps / 2;
    for (size_t t = timeOn; t < timeOff; ++t) {
        state.radE[state.idxTN(t, state.sourceIndex)] = 1.0f;
    }
}

// ============================================================================
// Precomputation Phase
// ============================================================================

void computeFormFactors(SimulationState& state) {
    printf("Computing form factors (Kij)...\n");

    const size_t N = state.numTriangles;
    const size_t numPairs = N * N;
    if (numPairs == 0) return;

    // The reference implementation feeds one sequential RNG through all (i, j)
    // pairs in row-major order. To reproduce that stream exactly in parallel,
    // the pair index space is split into contiguous chunks whose draw counts
    // are known up front (DRAWS_PER_PAIR per non-culled pair), and every chunk
    // is processed with a private RNG copy positioned at its stream offset.
    const size_t P = static_cast<size_t>(omp_get_max_threads());

    // Chunk layout: a cheap first wave (so all threads start almost at once),
    // full-size chunks in the middle, and a guided taper at the end.
    const size_t baseChunk = std::max<size_t>(32, (numPairs + 16 * P - 1) / (16 * P));
    const size_t smallChunk = std::max<size_t>(16, baseChunk / 8);
    std::vector<size_t> chunkBegin;
    chunkBegin.reserve(24 * P + 2);
    for (size_t pos = 0; pos < numPairs;) {
        const size_t remaining = numPairs - pos;
        size_t size = (chunkBegin.size() < 2 * P)
                          ? smallChunk
                          : std::clamp(remaining / (2 * P), smallChunk, baseChunk);
        size = std::min(size, remaining);
        chunkBegin.push_back(pos);
        pos += size;
    }
    chunkBegin.push_back(numPairs);
    const size_t numChunks = chunkBegin.size() - 1;

    // Checkpoints are published per group of GROUP chunks; a consumer skips
    // ahead over the preceding chunks of its group itself. This keeps the
    // sequential producer's per-chunk cost (copying a 2.5 KB engine state)
    // negligible compared to the block-twist discard it performs anyway.
    constexpr size_t GROUP = 8;
    const size_t numGroups = (numChunks + GROUP - 1) / GROUP;
    std::vector<unsigned long long> chunkDraws(numChunks, 0);
    std::vector<RandomGenerator> checkpoints(numGroups, RandomGenerator(42));
    std::atomic<size_t> groupsReady{0};
    std::atomic<size_t> nextChunk{0};
    std::atomic<size_t> pairsDone{0};
    const size_t progressStride = 100 * N;

    #pragma omp parallel
    {
        // Pass 1: draws consumed per chunk (cheap)
        #pragma omp for schedule(dynamic, 8)
        for (size_t c = 0; c < numChunks; ++c) {
            unsigned long long draws = 0;
            for (size_t p = chunkBegin[c]; p < chunkBegin[c + 1]; ++p) {
                const size_t i = p / N;
                const size_t j = p - i * N;
                if (i == j) continue;
                if (!cullSameDirection(state.triangles[i], state.triangles[j])) {
                    draws += DRAWS_PER_PAIR;
                }
            }
            chunkDraws[c] = draws;
        }

        // Pass 2a (thread 0): walk the stream once, publishing group checkpoints.
        // discard() only performs the block twist, ~700x cheaper per draw than
        // the ray casting it stands in for, so the producer stays well ahead of
        // the consumers and then joins them.
        if (omp_get_thread_num() == 0) {
            RandomGenerator streamRng(42);
            for (size_t g = 0; g < numGroups; ++g) {
                checkpoints[g] = streamRng;
                groupsReady.store(g + 1, std::memory_order_release);
                const size_t cEnd = std::min((g + 1) * GROUP, numChunks);
                for (size_t c = g * GROUP; c < cEnd; ++c) {
                    streamRng.discard(chunkDraws[c]);
                }
            }
        }

        // Pass 2b (all threads): consume chunks in order.
        for (;;) {
            const size_t c = nextChunk.fetch_add(1, std::memory_order_relaxed);
            if (c >= numChunks) break;
            const size_t g = c / GROUP;

            while (groupsReady.load(std::memory_order_acquire) <= g) cpuRelax();

            RandomGenerator rng = checkpoints[g];
            unsigned long long skip = 0;
            for (size_t cc = g * GROUP; cc < c; ++cc) skip += chunkDraws[cc];
            rng.discard(skip);

            const size_t begin = chunkBegin[c];
            const size_t end = chunkBegin[c + 1];
            for (size_t p = begin; p < end; ++p) {
                const size_t i = p / N;
                const size_t j = p - i * N;
                if (i == j) continue;
                state.kij[p] = computeKij(i, j, state.triangles, state.octree, rng);
            }

            const size_t len = end - begin;
            const size_t done = pairsDone.fetch_add(len, std::memory_order_relaxed) + len;
            if (done == numPairs) {
                printf("  Progress: %zu/%zu triangles\n", N, N);
            } else if (done / progressStride > (done - len) / progressStride) {
                printf("  Progress: %zu/%zu triangles\n", (done / progressStride) * 100, N);
            }
        }
    }
}

void computeTimeDelays(SimulationState& state) {
    printf("Computing time delays (Tau)...\n");

    int minTau = std::numeric_limits<int>::max();
    #pragma omp parallel for schedule(static) reduction(min : minTau)
    for (size_t i = 0; i < state.numTriangles; ++i) {
        for (size_t j = 0; j < state.numTriangles; ++j) {
            if (i == j) continue;
            const int tauij = computeTau(state.triangles[i], state.triangles[j]);
            state.tau[state.idx2d(i, j)] = tauij;
            minTau = std::min(minTau, tauij);
        }
    }
    state.minTau = minTau;
}

// ============================================================================
// Simulation Phase (Wave Propagation)
// ============================================================================

void runSimulation(SimulationState& state) {
    printf("Running wave propagation simulation...\n");

    const size_t N = state.numTriangles;
    const size_t T = state.numTimesteps;
    const val_t* __restrict kijM = state.kij.data();
    const int* __restrict tauM = state.tau.data();
    const val_t* __restrict areas = state.areas.data();
    const val_t* __restrict rho = state.rho.data();
    const val_t* __restrict radE = state.radE.data();
    val_t* __restrict radB = state.radB.data();

    // Timesteps are strictly ordered, but when every off-diagonal delay is at
    // least one timestep (always true for distinct triangle centers) radB[t]
    // depends only on earlier timesteps, so all triangles within a timestep are
    // independent. The per-triangle summation order over j is preserved. In the
    // degenerate zero-delay case a single thread sweeps the rows in the original
    // order, which reproduces the sequential semantics exactly.
    // Static row partition: identical to the first-touch partition used when
    // the kij/tau matrices were initialized, so each thread sweeps local memory.
    const int nt = (state.minTau >= 1) ? state.simThreads : 1;
    #pragma omp parallel num_threads(nt)
    {
        for (size_t t = 0; t < T; ++t) {
            #pragma omp for schedule(static)
            for (size_t i = 0; i < N; ++i) {
                val_t sumB = ZERO;
                const val_t* __restrict kijRow = kijM + i * N;
                const int* __restrict tauRow = tauM + i * N;

                for (size_t j = 0; j < N; ++j) {
                    if (i == j) continue;

                    int tauij = tauRow[j];

                    // Skip if wave hasn't yet propagated from j to i
                    if (static_cast<int>(t) < tauij) continue;

                    val_t kij = kijRow[j];
                    if (kij <= ZERO) continue;

                    // Get radiosity from source triangle at time when emission occurred
                    size_t srcTime = t - static_cast<size_t>(tauij);
                    val_t radJ = radB[srcTime * N + j];
                    if (radJ <= ZERO) continue;

                    // Accumulate contribution: form factor * area * source radiosity
                    sumB += std::min(kij * areas[j], ONE) * radJ;
                }

                // Update radiosity: reflection + emission
                radB[t * N + i] = rho[i] * sumB + radE[t * N + i];
            }
            // (implicit barrier of the worksharing loop orders timesteps)

            #pragma omp master
            if ((t + 1) % 10 == 0 || t + 1 == T) {
                printf("  Timestep %zu/%zu\n", t + 1, T);
            }
        }
    }
}

// ============================================================================
// Distance Computation (Cross-Correlation)
// ============================================================================

void computeDistances(SimulationState& state) {
    printf("Computing distances via cross-correlation...\n");

    const size_t N = state.numTriangles;
    const size_t T = state.numTimesteps;

    // Transpose radB (T x N) to per-triangle time series (N x T) so that the
    // correlation loops stream through contiguous memory.
    std::vector<val_t> series(N * T);
    const int nt = teamSizeForWork(N * T * T, 32768);
    #pragma omp parallel for schedule(static) num_threads(nt)
    for (size_t i = 0; i < N; ++i) {
        for (size_t t = 0; t < T; ++t) {
            series[i * T + t] = state.radB[state.idxTN(t, i)];
        }
    }
    const val_t* __restrict src = series.data() + state.sourceIndex * T;

    #pragma omp parallel for schedule(dynamic, 8) num_threads(nt)
    for (size_t i = 0; i < N; ++i) {
        const val_t* __restrict sB = series.data() + i * T;
        val_t maxCorr = ZERO;
        int bestT = 0;

        // Discrete cross-correlation to find time delay
        for (size_t t = 0; t < T; ++t) {
            val_t sum = ZERO;

            for (size_t tt = t; tt < T; ++tt) {
                val_t pB = sB[tt];
                val_t pS = src[tt - t];
                sum += pS * pB;
            }

            if (sum > maxCorr) {
                maxCorr = sum;
                bestT = static_cast<int>(t);
            }
        }

        state.distances[i] = WAVE_SPEED * static_cast<val_t>(bestT);
    }
}

// ============================================================================
// Validation
// ============================================================================

bool validateResults(const SimulationState& state) {
    printf("\nValidation:\n");

    // Check that distances are non-negative
    bool allNonNegative = true;
    val_t minDist = std::numeric_limits<val_t>::max();
    val_t maxDist = std::numeric_limits<val_t>::lowest();
    val_t sumDist = ZERO;
    int nonZeroCount = 0;

    for (size_t i = 0; i < state.numTriangles; ++i) {
        val_t d = state.distances[i];
        if (d < 0) {
            allNonNegative = false;
            printf("  ERROR: Negative distance at triangle %zu: %f\n", i, d);
        }
        if (!std::isfinite(d)) {
            printf("  ERROR: Non-finite distance at triangle %zu: %f\n", i, d);
            return false;
        }
        minDist = std::min(minDist, d);
        maxDist = std::max(maxDist, d);
        sumDist += d;
        if (d > EPSILON) nonZeroCount++;
    }

    printf("  Distance range: [%.4f, %.4f]\n", minDist, maxDist);
    printf("  Average distance: %.4f\n", sumDist / static_cast<val_t>(state.numTriangles));
    printf("  Non-zero distances: %d/%zu\n", nonZeroCount, state.numTriangles);

    // Check source distance is zero or very small
    val_t srcDist = state.distances[state.sourceIndex];
    if (srcDist > WAVE_SPEED * 2) {
        printf("  WARNING: Source triangle distance is non-zero: %.4f\n", srcDist);
    }

    // Check radiosity propagation (some triangles should have received energy)
    int receivedEnergy = 0;
    for (size_t i = 0; i < state.numTriangles; ++i) {
        for (size_t t = 0; t < state.numTimesteps; ++t) {
            if (state.radB[state.idxTN(t, i)] > EPSILON) {
                receivedEnergy++;
                break;
            }
        }
    }

    printf("  Triangles receiving energy: %d/%zu\n", receivedEnergy, state.numTriangles);

    if (receivedEnergy == 0) {
        printf("  ERROR: No triangles received energy - simulation failed\n");
        return false;
    }

    // Check Kij matrix (should have some non-zero entries)
    int nonZeroKij = 0;
    for (size_t i = 0; i < state.numTriangles * state.numTriangles; ++i) {
        if (state.kij[i] > EPSILON) nonZeroKij++;
    }
    printf("  Non-zero form factors: %d/%zu (%.2f%%)\n",
           nonZeroKij, state.numTriangles * state.numTriangles,
           100.0f * nonZeroKij / static_cast<val_t>(state.numTriangles * state.numTriangles));

    if (nonZeroKij == 0) {
        printf("  ERROR: All form factors are zero - visibility computation failed\n");
        return false;
    }

    if (!allNonNegative) {
        return false;
    }

    printf("  Validation: PASSED\n");
    return true;
}

// ============================================================================
// Hash for Verification
// ============================================================================

uint64_t computeHash(const SimulationState& state) {
    uint64_t hash = 0;
    for (size_t i = 0; i < state.numTriangles; ++i) {
        const uint32_t* ptr = reinterpret_cast<const uint32_t*>(&state.distances[i]);
        hash ^= (static_cast<uint64_t>(*ptr) + i) * 0x9e3779b97f4a7c15ULL;
    }
    return hash;
}

// ============================================================================
// Helper: Compute subdivision level from target triangle count
// ============================================================================

int getSubdivisionsForTriangleCount(int targetTriangles) {
    // Icosphere: 20 triangles initially, 4x per subdivision
    // subdivisions: 0->20, 1->80, 2->320, 3->1280, 4->5120, 5->20480
    int subdivisions = 0;
    int triangles = 20;
    while (triangles < targetTriangles && subdivisions < 6) {
        subdivisions++;
        triangles *= 4;
    }
    return subdivisions;
}


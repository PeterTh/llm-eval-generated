// QT Clustering Benchmark - CUDA-parallel version
//
// QT (Quality Threshold) clustering is an algorithm that builds clusters
// by starting with a seed point and iteratively adding the closest point
// that maintains the cluster's diameter below a threshold.
//
// GPU mapping:
//   * Each round, every unclustered point is evaluated as a seed. Each seed
//     is grown by one CUDA thread block (seeds are independent within a round).
//   * Inside a block, the per-candidate max distance to the cluster is kept
//     incrementally (max is exact, so this equals the original recomputation),
//     and the closest admissible candidate is found with a block-wide argmin
//     reduction using the same tie-break as the sequential code (lowest index).
//   * The best seed (largest cluster, earliest index on ties) is chosen on the
//     host, and its members are regenerated by one additional block launch.
//   * The pairwise-diameter validation is also computed on the GPU.

